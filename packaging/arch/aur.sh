#!/bin/bash
# Write the AUR's PKGBUILD for PKG (owly, omdrop-owl or omdrop-owl-bin), and
# the install file it names, into DIR. For owly and omdrop-owl, it's
# packaging/arch/PKG/PKGBUILD changed to build the release tagged
# v<pkgver> instead of this checkout. omdrop-owl-bin's is the AUR's
# already, and is checked instead. The
# tarball's checksum is left SKIP, for updpkgsums to fill in once the tag
# exists (aur-publish.sh).
#
#   packaging/arch/aur.sh PKG DIR
set -eu

HERE=$(cd "$(dirname "$0")" && pwd)
PKG=${1:?usage: packaging/arch/aur.sh owly|omdrop-owl|omdrop-owl-bin DIR}
OUT=${2:?usage: packaging/arch/aur.sh owly|omdrop-owl|omdrop-owl-bin DIR}
case "$PKG" in
  owly | omdrop-owl) TAG='v${pkgver}' ;;
  omdrop-owl-bin) ;;
  *) echo "packaging/arch/aur.sh: no package $PKG" >&2; exit 2 ;;
esac
SRC=$HERE/$PKG/PKGBUILD
VERSION=$(sed -n 's/^pkgver=//p' "$SRC")
mkdir -p "$OUT"

# omdrop-owl-bin has owly's and omdrop-owl's files (packaging/package.sh tar),
# so it has to stay their sum: their version, both packages' depends,
# the optdepends those don't cover, both licenses, and the functions its
# install file takes from theirs unchanged.
if [ "$PKG" = omdrop-owl-bin ]; then
  # One of a PKGBUILD's variables, an entry a line (none if it's unset).
  _array() { ( source "$HERE/$1/PKGBUILD" && declare -n a="$2" && printf '%s\n' "${a[@]}" ) | sed '/^$/d' | sort -u; }
  _want() {
    case "$1" in
      pkgver) { _array owly pkgver; _array omdrop-owl pkgver; } ;;
      depends) { _array owly depends; _array omdrop-owl depends; } | grep -vx owly ;;
      optdepends)
        { _array owly optdepends; _array omdrop-owl optdepends; } | while IFS= read -r o; do
          _want depends | grep -qx "${o%%:*}" || echo "$o"
        done
        ;;
      license) { _array owly license; _array omdrop-owl license; } ;;
    esac | sort -u
  }
  for field in pkgver depends optdepends license; do
    if ! diff <(_want "$field") <(_array "$PKG" "$field") >&2; then
      echo "packaging/arch/aur.sh: $PKG's $field isn't owly's and omdrop-owl's together (<: theirs, >: its)" >&2
      exit 1
    fi
  done
  _function() { sed -n "/^$1() {/,/^}/p" "$HERE/$2/$2.install"; }
  for taken in owly:post_upgrade omdrop-owl:_migrate_settings; do
    from=${taken%%:*} fn=${taken#*:}
    if [ -z "$(_function "$fn" "$from")" ] || ! diff <(_function "$fn" "$from") <(_function "$fn" "$PKG") >&2; then
      echo "packaging/arch/aur.sh: $PKG.install's $fn isn't $from.install's" >&2
      exit 1
    fi
  done
  cp "$SRC" "$HERE/$PKG/$PKG.install" "$OUT/"
  exit 0
fi

# Each change has to apply, so a PKGBUILD edit that sidesteps one fails here
# rather than publishing something half converted.
TARBALL='${pkgname}-${pkgver}.tar.gz'
awk -v tag="$TAG" -v tarball="$TARBALL" -v ver="$VERSION" -v pkg="$PKG" '
  /^# Build this checkout:/ {
    print "# Generated by packaging/arch/aur.sh from packaging/arch/" pkg "/PKGBUILD"
    print "# in https://github.com/t4t5/owly, at " pkg " " ver ": change it there."
    header++; next
  }
  /^source=\(/ { print "noextract=(\"" tarball "\")" }
  sub(/^source=\(/, "source=(\"" tarball "::${url}/archive/refs/tags/" tag ".tar.gz\"\n        ") { source++ }
  sub(/^sha256sums=\(/, "sha256sums=(\047SKIP\047 ") { sums++ }
  /# aur: tree$/ { print "_tree() { echo \"${srcdir}/${pkgname}-${pkgver}\"; }"; tree++; next }
  /# aur: unpack$/ {
    print "_unpack() {"
    print "  rm -rf \"$(_tree)\" && mkdir -p \"$(_tree)\""
    print "  tar -xzf \"${srcdir}/" tarball "\" -C \"$(_tree)\" --strip-components=1"
    print "}"
    unpack++; next
  }
  { print }
  END { exit !(header == 1 && source == 1 && sums == 1 && tree == 1 && unpack == 1) }
' "$SRC" > "$OUT/PKGBUILD" \
  || { echo "packaging/arch/aur.sh: $PKG's PKGBUILD no longer has the shape this expects" >&2; exit 1; }
if grep -n startdir "$OUT/PKGBUILD" >&2; then
  echo "packaging/arch/aur.sh: the AUR's PKGBUILD can't use \${startdir}: use \$(_tree)" >&2
  exit 1
fi
cp "$HERE/$PKG/$PKG.install" "$OUT/"
